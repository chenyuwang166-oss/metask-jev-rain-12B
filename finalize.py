"""Maintainer tool: inject fitted parameters, record the freeze and rebuild MANIFEST.sha256.

  python3 -B finalize.py fitted.release.json   inject fitted parameters, then record the freeze
  python3 -B finalize.py --freeze-record       record FREEZE.md from the current files and rebuild the manifest

No model is loaded. fitted.example.json holds sample values used only by the offline checks.
"""
import argparse
import copy
import fnmatch
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
from package_files import package_files
from core import load_config, threshold_identity, validate_config, validate_threshold, validate_calibration
from launch import IMAGE

ROOT = Path(__file__).resolve().parent
KEY = 'gemma-4-12b-awq'

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def ignored_patterns(root):
    """Name patterns of .gitignore (all of them are simple names, globs or directory names)."""
    path=Path(root)/'.gitignore'
    if not path.is_file():return []
    return [line.strip().rstrip('/') for line in path.read_text(encoding='utf-8').splitlines()
            if line.strip() and not line.startswith('#')]

def files(root=ROOT):
    """Package members in a platform-independent order; a file git would ignore is refused, so the
    manifest of a working tree equals the manifest of a clone of the commit."""
    patterns=ignored_patterns(root)
    for p in sorted(package_files(root),key=lambda path:path.relative_to(root).as_posix()):
        if p.is_symlink():
            raise ValueError('Symlinks are not allowed in a freeze')
        rel=p.relative_to(root).parts
        if '__pycache__' in rel or rel[0].startswith('selftest-') or p.suffix in ('.pyc','.tmp'):
            raise ValueError('Runtime output in package: '+rel[0])
        if any(fnmatch.fnmatch(part,pattern) for part in rel for pattern in patterns):
            raise ValueError('File ignored by .gitignore in package: '+p.relative_to(root).as_posix())
        if p.is_file() and p.name != 'MANIFEST.sha256':
            yield p

def replace_text(path, text):
    """Write through an exclusively created sibling file, then rename it over the target."""
    tmp=path.with_name(path.name+'.tmp')
    with tmp.open('x',encoding='utf-8',newline='\n') as out:
        out.write(text);out.flush();os.fsync(out.fileno())
    os.replace(tmp,path)

def freeze(root=ROOT):
    # A manifest cannot contain its own hash. FREEZE is hashed by MANIFEST.
    text=''.join(f'{digest(p)}  {p.relative_to(root).as_posix()}\n' for p in files(root))
    replace_text(root/'MANIFEST.sha256',text)

def freeze_record():
    """FREEZE.md states the hashes of the files as delivered; pkg_check --release compares them."""
    list(files())  # Reject runtime artifacts before any write.
    raw=json.loads((ROOT/'config.json').read_text(encoding='utf-8'))
    package=raw.get('package',{})
    status='SAMPLE ONLY' if package.get('sample_only') else 'PARAMETERS FITTED' if package.get('finalized') else 'NOT FINALIZED'
    now=datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    replace_text(ROOT/'FREEZE.md',
        '# metask-jev-rain-12B freeze record\n\n'
        'Generated by `python3 -B finalize.py --freeze-record` from the files in this package.\n\n'
        'Status: '+status+'\n\n'
        'Recorded (UTC): '+now+'\n\n'
        'Runtime image: '+IMAGE+'\n\n'
        'config.json SHA256: '+digest(ROOT/'config.json')+'\n\n'
        'calibration.json SHA256: '+digest(ROOT/'calibration.json')+'\n\n'
        'prompt_sha: '+threshold_identity(load_config())['prompt_sha']+'\n\n'
        'MANIFEST.sha256 lists every package file except itself, including this file; '
        'check with `sha256sum -c MANIFEST.sha256`.\n')
    freeze()

def number(v, name, lo=0, hi=None):
    if type(v) not in (int,float) or not math.isfinite(v) or v < lo or (hi is not None and v > hi):
        raise ValueError('Invalid fitted field: '+name)
    return v

def finalize(fitted, sample=False):
    list(files())  # Reject runtime artifacts before any mutation.
    raw=json.loads((ROOT/'config.json').read_text(encoding='utf-8'))
    c=load_config()
    ident=threshold_identity(c)
    if fitted.get('sample_only',False) != sample:
        raise ValueError('Sample parameters require --sample; never submit sample output')
    if fitted.get('prompt_sha') != ident['prompt_sha']:
        raise ValueError('prompt_sha does not match packaged renderer')
    for key in ('backend','quant','model_key'):
        if fitted.get(key)!=ident[key]: raise ValueError('Fitted identity mismatch: '+key)
    threshold=number(fitted['threshold'],'threshold')
    achieved=number(fitted['achieved'],'achieved',0,1)
    if fitted['quota']!=.15 or fitted['fuse']!=.20:
        raise ValueError('This submission requires quota=0.15 and fuse=0.20')
    if fitted.get('n')!=231: raise ValueError('Expected 231 public calibration decisions')
    ident.update(placeholder=False, achieved=achieved, achieved_share=achieved, n=231,
                 fitted_on=fitted.get('fitted_on','sample'))
    raw['bench']['target_slow_share']=.15
    raw['profiles'][KEY].setdefault('bench',{})['target_slow_share']=.15
    for r in (raw['routing'],raw['profiles'][KEY]['routing']):
        r.update(margin_threshold=threshold,margin_threshold_fitted_for=ident,
                 quota=fitted['quota'],fuse=fitted['fuse'],target_slow_share=.15)
    blocks={}
    for name in ('fast','slow','fallback'):
        b=fitted['calibration'][name]
        pc=number(b['p_cal'],name+'.p_cal',.5,1)
        tc=number(b['T_choice'],name+'.T_choice',1e-12)
        ts=number(b['T_score'],name+'.T_score',1e-12)
        block=copy.deepcopy(b)
        for field in ('p_cal','T_choice','T_score'):block.pop(field,None)
        block['source_placeholder']=b.get('placeholder',sample)
        block.update(placeholder=sample, held_out_validated=False,
                     status='SAMPLE ONLY' if sample else b.get('status','candidate; held-out validation required'),
                     validation_status=b.get('validation_status','candidate; held-out validation required'),
                     noul_calibration=dict(b.get('noul_calibration',{}),p_cal=pc),
                     temperature_by_kind=dict(b.get('temperature_by_kind',{}),noul='one_bin',choice=tc,score=ts))
        blocks[name]=block
    cal={'status':'SAMPLE ONLY' if sample else fitted.get('calibration_status','candidate; held-out validation required'),
         'held_out_validated':False,
         'models':{KEY:dict(blocks,placeholder=sample,fitted_for=ident,status=fitted.get('model_calibration_status','candidate; held-out validation required'))}}
    from core import apply_profile
    checked=copy.deepcopy(raw);apply_profile(checked)
    validate_config(checked);validate_threshold(checked)
    for name in blocks: validate_calibration(cal,KEY,name)
    raw['package']['finalized']=not sample
    raw['package']['sample_only']=sample
    for name,value in [('config.json',raw),('calibration.json',cal)]:
        replace_text(ROOT/name,json.dumps(value,ensure_ascii=False,indent=2,allow_nan=False)+'\n')
    freeze_record()

def main():
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('fitted',nargs='?',type=Path);p.add_argument('--sample',action='store_true')
    p.add_argument('--freeze-record',action='store_true',help='record FREEZE.md and MANIFEST.sha256 from the current files')
    a=p.parse_args()
    if a.freeze_record:
        if a.fitted or a.sample:p.error('--freeze-record takes no other arguments')
        freeze_record();print('FREEZE.md and MANIFEST.sha256 recorded.');return
    if not a.fitted:p.error('fitted JSON required')
    finalize(json.loads(a.fitted.read_text(encoding='utf-8')),a.sample)
    print('Finalization complete; FREEZE.md and MANIFEST.sha256 recorded.')

if __name__=='__main__':main()
